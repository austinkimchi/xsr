#!/usr/bin/env python3
"""Generate a verifier-friendly Unicode alphanumeric bitmap for BPF."""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path


def word_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for codepoint in range(sys.maxunicode + 1):
        if chr(codepoint).isalnum():
            if start is None:
                start = codepoint
        elif start is not None:
            ranges.append((start, codepoint - 1))
            start = None
    if start is not None:
        ranges.append((start, sys.maxunicode))
    return ranges


def contains(ranges: list[tuple[int, int]], codepoint: int) -> bool:
    left, right = 0, len(ranges)
    while left < right:
        middle = (left + right) // 2
        first, last = ranges[middle]
        if codepoint < first:
            right = middle
        elif codepoint > last:
            left = middle + 1
        else:
            return True
    return False


def word_bitmap(ranges: list[tuple[int, int]]) -> list[int]:
    words = [0] * ((sys.maxunicode + 1 + 63) // 64)
    for first, last in ranges:
        for codepoint in range(first, last + 1):
            words[codepoint >> 6] |= 1 << (codepoint & 63)
    return words


def emit(ranges: list[tuple[int, int]]) -> str:
    words = word_bitmap(ranges)
    lines = []
    for offset in range(0, len(words), 8):
        values = ", ".join(
            f"0x{word:016x}ULL" for word in words[offset : offset + 8]
        )
        lines.append(f"  {values},")
    return "\n".join(
        [
            "/* Generated by benchmarks/policy/generate_unicode_word_header.py. Do not edit. */",
            f"/* Python Unicode database: {unicodedata.unidata_version}. */",
            "#ifndef XDP_UNICODE_WORD_GENERATED_H",
            "#define XDP_UNICODE_WORD_GENERATED_H",
            "",
            f"#define XDP_UNICODE_WORD_MAX {sys.maxunicode}U",
            f"#define XDP_UNICODE_WORD_BITMAP_WORDS {len(words)}",
            "static const __u64 xdp_unicode_word_bitmap[XDP_UNICODE_WORD_BITMAP_WORDS] = {",
            *lines,
            "};",
            "",
            "#endif",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(emit(word_ranges()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
