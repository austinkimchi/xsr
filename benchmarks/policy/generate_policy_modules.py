#!/usr/bin/env python3
"""Select and generate independently compiled keyword-routing modules."""

from __future__ import annotations

import argparse
from pathlib import Path

from generate_bm25_policy_header import emit as emit_bm25, parse as parse_bm25
from generate_jaccard_policy_header import emit as emit_ngram, parse as parse_ngram
from generate_keyword_header import decision_keyword_routes, keyword_signals, load_policy
from generate_unicode_word_header import emit as emit_unicode_words, word_ranges


SUPPORTED = {"ngram", "bm25"}
PROFILES = {"auto", "ngram", "bm25", "intent", "mixed"}


def methods(path: Path) -> set[str]:
    policy = load_policy(path)
    signals = keyword_signals(policy)
    selected = {
        str(signal.get("method", "")).lower()
        for signal in signals
        if isinstance(signal, dict)
    }
    unknown = selected - SUPPORTED
    if unknown:
        raise ValueError(f"eBPF keyword modules do not support: {', '.join(sorted(unknown))}")
    if not selected:
        raise ValueError("policy must select at least one keyword method")

    _, decision_priorities = decision_keyword_routes(policy)
    priority_methods: dict[int, str] = {}
    for signal in signals:
        if not isinstance(signal, dict):
            continue
        method = str(signal.get("method", "")).lower()
        name = str(signal.get("name", ""))
        priority = decision_priorities.get(name, int(signal.get("priority", 0)))
        previous_method = priority_methods.setdefault(priority, method)
        if previous_method != method:
            raise ValueError(
                f"priority {priority} is shared by {previous_method} and {method} rules; "
                "mixed keyword methods require distinct priorities"
            )
    return selected


def resolve_profile(path: Path, requested: str) -> tuple[str, set[str]]:
    if requested not in PROFILES:
        raise ValueError(f"signal profile must be one of: {', '.join(sorted(PROFILES))}")
    if requested == "intent":
        return requested, set()
    selected = methods(path)
    inferred = next(iter(selected)) if len(selected) == 1 else "mixed"
    effective = inferred if requested == "auto" else requested
    if effective in SUPPORTED and selected != {effective}:
        raise ValueError(
            f"signal profile {effective!r} contradicts policy methods "
            f"{', '.join(sorted(selected))!r}"
        )
    if effective == "mixed" and not selected:
        raise ValueError("mixed signal profile requires at least one keyword method")
    return effective, selected


def selection_header(
    path: Path, profile: str | set[str], selected: set[str] | None = None,
    parity_debug: bool = False, enable_distill: bool | None = None,
) -> str:
    # Keep the helper convenient for policy unit tests and external tooling that
    # historically passed only the selected method set.
    if isinstance(profile, set):
        selected = profile
        profile = next(iter(selected)) if len(selected) == 1 else "mixed"
    assert selected is not None
    if parity_debug and profile not in {"intent", "mixed"}:
        raise ValueError("distill parity diagnostics require an intent or mixed signal profile")
    if enable_distill is None:
        enable_distill = profile in {"intent", "mixed"}
    return "\n".join(
        [
            "/* Generated by generate_policy_modules.py. Do not edit. */",
            f"/* Source: {path.as_posix()} */",
            "#ifndef XDP_KEYWORD_MODULES_GENERATED_H",
            "#define XDP_KEYWORD_MODULES_GENERATED_H",
            f'#define XDP_SIGNAL_PROFILE_NAME "{profile}"',
            f"#define XDP_SIGNAL_ENABLE_NGRAM {int(profile in {'ngram', 'mixed'} and 'ngram' in selected)}",
            f"#define XDP_SIGNAL_ENABLE_BM25 {int(profile in {'bm25', 'mixed'} and 'bm25' in selected)}",
            f"#define XDP_SIGNAL_ENABLE_DISTILL {int(enable_distill)}",
            f"#define XSR_DISTILL_PARITY_DEBUG {int(parity_debug)}",
            f"#define XDP_KEYWORD_ENABLE_NGRAM {int(profile in {'ngram', 'mixed'} and 'ngram' in selected)}",
            f"#define XDP_KEYWORD_ENABLE_BM25 {int(profile in {'bm25', 'mixed'} and 'bm25' in selected)}",
            "#endif",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("policy", type=Path)
    parser.add_argument("output_dir", type=Path, nargs="?")
    parser.add_argument("--signal-profile", default="auto", choices=sorted(PROFILES))
    parser.add_argument("--parity-debug", action="store_true")
    parser.add_argument("--resolve-only", action="store_true")
    args = parser.parse_args()
    profile, selected = resolve_profile(args.policy, args.signal_profile)
    if args.resolve_only:
        print(profile)
        return 0
    if args.output_dir is None:
        parser.error("output_dir is required unless --resolve-only is used")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "xdp_keyword_modules.generated.h").write_text(
        selection_header(
            args.policy, profile, selected, args.parity_debug,
            enable_distill=profile in {"intent", "mixed"},
        )
    )
    if "ngram" in selected:
        rules, keywords, casefolds = parse_ngram(args.policy, allow_other_methods=True)
        (args.output_dir / "xdp_jaccard_policy.generated.h").write_text(
            emit_ngram(args.policy, rules, keywords, casefolds)
        )
        (args.output_dir / "xdp_unicode_word.generated.h").write_text(
            emit_unicode_words(word_ranges())
        )
    if "bm25" in selected:
        rules, documents, terms = parse_bm25(args.policy)
        (args.output_dir / "xdp_bm25_policy.generated.h").write_text(
            emit_bm25(args.policy, rules, documents, terms)
        )
    print(f"signal profile: {profile}; keyword modules: " + (", ".join(sorted(selected)) or "none"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
