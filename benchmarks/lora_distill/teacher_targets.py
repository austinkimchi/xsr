#!/usr/bin/env python3
"""Verify and run the frozen official mmBERT-32K + intent LoRA teacher."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from core import LABELS, read_jsonl, stable_softmax

BASE_ID = "llm-semantic-router/mmbert-32k-yarn"
BASE_REVISION = "72a23a6640489471eb4ff7ad3ec5bc80af8a27de"
ADAPTER_ID = "llm-semantic-router/mmbert32k-intent-classifier-lora"
ADAPTER_REVISION = "81eb867a46864aea8f95b77d7e2618ef0bed09e5"


def verify_metadata() -> dict:
    from huggingface_hub import hf_hub_download

    loaded = {}
    for filename in ("adapter_config.json", "label_mapping.json", "category_mapping.json"):
        path = hf_hub_download(ADAPTER_ID, filename, revision=ADAPTER_REVISION)
        loaded[filename] = json.loads(Path(path).read_text())
    adapter = loaded["adapter_config.json"]
    expected = {str(index): label for index, label in enumerate(LABELS)}
    for filename in ("label_mapping.json", "category_mapping.json"):
        if loaded[filename].get("idx_to_category") != expected:
            raise RuntimeError(f"published {filename} ordering does not match the 14-class contract")
    if adapter.get("base_model_name_or_path") != BASE_ID or adapter.get("task_type") != "SEQ_CLS":
        raise RuntimeError("adapter does not identify the expected fixed sequence-classification base")
    tokenizer_path = Path(hf_hub_download(ADAPTER_ID, "tokenizer.json", revision=ADAPTER_REVISION))
    tokenizer_sha256 = hashlib.sha256(tokenizer_path.read_bytes()).hexdigest()
    if tokenizer_sha256 != "17f7d8b9518c403d7429ad9eeeabb6eed49c8d3311de8ef4ed5ad811381a2ced":
        raise RuntimeError("official tokenizer hash does not match recorded provenance")
    return {
        "base_model": BASE_ID, "base_revision": BASE_REVISION,
        "adapter": ADAPTER_ID, "adapter_revision": ADAPTER_REVISION,
        "tokenizer": ADAPTER_ID, "tokenizer_revision": ADAPTER_REVISION,
        "tokenizer_sha256": tokenizer_sha256, "labels": list(LABELS),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--provenance", type=Path, required=True)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--limit", type=int, help="smoke-test only; omit for the complete manifest")
    parser.add_argument("--resume", action="store_true", help="append targets missing from an existing output")
    parser.add_argument(
        "--reuse-targets", type=Path,
        help="seed a new output with matching frozen-teacher targets from this JSONL",
    )
    parser.add_argument(
        "--reuse-provenance", type=Path,
        help="provenance JSON paired with --reuse-targets; must match the current teacher",
    )
    parser.add_argument("--no-length-sort", action="store_true", help="disable padding-efficient length bucketing")
    args = parser.parse_args()
    provenance = verify_metadata()
    if bool(args.reuse_targets) != bool(args.reuse_provenance):
        raise ValueError("--reuse-targets and --reuse-provenance must be provided together")
    if args.reuse_provenance:
        reused_provenance = json.loads(args.reuse_provenance.read_text())
        if reused_provenance != provenance:
            raise RuntimeError("reused targets were generated by different teacher provenance")
    args.provenance.parent.mkdir(parents=True, exist_ok=True)
    args.provenance.write_text(json.dumps(provenance, indent=2) + "\n")

    import torch
    from peft import PeftModel
    from transformers import AutoModelForSequenceClassification, AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(ADAPTER_ID, revision=ADAPTER_REVISION)
    base = AutoModelForSequenceClassification.from_pretrained(
        BASE_ID, revision=BASE_REVISION, num_labels=len(LABELS)
    )
    model = PeftModel.from_pretrained(base, ADAPTER_ID, revision=ADAPTER_REVISION)
    device = args.device if args.device != "cuda" or torch.cuda.is_available() else "cpu"
    model.to(device).eval()
    rows = list(read_jsonl(args.manifest))
    manifest_keys = {row["normalized_sha256"] for row in rows}
    if args.limit is not None:
        rows = rows[: args.limit]
    selected_keys = {row["normalized_sha256"] for row in rows}
    completed = set()
    reusable = []
    if args.reuse_targets:
        if args.resume:
            raise ValueError("--reuse-targets and --resume are mutually exclusive")
        reusable = [
            row for row in read_jsonl(args.reuse_targets)
            if row["normalized_sha256"] in selected_keys
        ]
        completed = {row["normalized_sha256"] for row in reusable}
        if len(completed) != len(reusable):
            raise RuntimeError("reuse target file contains duplicate matching prompts")
    if args.resume and args.output.exists():
        completed = {row["normalized_sha256"] for row in read_jsonl(args.output)}
        if not completed <= manifest_keys:
            raise RuntimeError("resume output contains targets outside this manifest")
    rows = [row for row in rows if row["normalized_sha256"] not in completed]
    if not args.no_length_sort:
        rows.sort(key=lambda row: len(tokenizer(
            row["prompt"], add_special_tokens=True, truncation=True, max_length=32_768
        )["input_ids"]))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    mode = "a" if args.resume else "w"
    processed = len(completed)
    with args.output.open(mode, encoding="utf-8") as stream, torch.inference_mode():
        for item in reusable:
            stream.write(json.dumps(item, separators=(",", ":")) + "\n")
        stream.flush()
        for start in range(0, len(rows), args.batch_size):
            batch = rows[start : start + args.batch_size]
            encoded = tokenizer(
                [row["prompt"] for row in batch], padding=True, truncation=True,
                max_length=32_768, return_tensors="pt",
            ).to(device)
            logits = model(**encoded).logits.detach().cpu().float().numpy()
            if logits.shape[1] != len(LABELS):
                raise RuntimeError(f"teacher emitted {logits.shape[1]} logits, expected 14")
            for row, values in zip(batch, logits):
                probabilities = stable_softmax(values)
                item = {
                    "normalized_sha256": row["normalized_sha256"],
                    "teacher_logits": values.tolist(),
                    "teacher_probability": probabilities.tolist(),
                    "teacher_top1_intent": LABELS[int(values.argmax())],
                }
                stream.write(json.dumps(item, separators=(",", ":")) + "\n")
            stream.flush()
            done = processed + min(start + args.batch_size, len(rows))
            print(f"teacher targets: {done}/{processed + len(rows)}")


if __name__ == "__main__":
    main()
